const productValidationSchema = Joi.object({
  name: Joi.string().required(),
  description: Joi.string().allow(null, ''),
  underwriter: Joi.string().valid(...underwriters).required(),
  agentcode: Joi.string().required(),
  basePremium: Joi.number().positive().allow(null),
  premium_annual: Joi.number().positive().allow(null),
  coverPeriod: Joi.string().allow(null, ''),
  vehicleClass: Joi.array().items(Joi.string().valid(...vehicleClasses)).required(),
  coverage: Joi.array().items(Joi.string().valid('THIRD_PARTY_ONLY', 'THIRD_PARTY_FIRE_AND_THEFT', 'COMPREHENSIVE')).required(),
  passengers: Joi.number().integer().allow(null),
  tonnage: Joi.number().integer().allow(null),
  minAge: Joi.number().integer().allow(null),
  maxAge: Joi.number().integer().allow(null),
  minValue: Joi.number().positive().allow(null),
  maxValue: Joi.number().positive().allow(null),
  ExcludedMakes: Joi.array().items(Joi.string()).allow(null),
  yearOfManufacture: Joi.any().forbidden() // explicitly forbid on product creation
});

module.exports = productValidationSchema;
